const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const path=require('node:path');
const source=fs.readFileSync(path.join(__dirname,'../rental-admin.html'),'utf8');
const common=fs.readFileSync(path.join(__dirname,'../rental-common.js'),'utf8');
const ctx={window:{location:{origin:'https://example.test',pathname:'/rental-admin.html'}},document:{getElementById(){return null;}},localStorage:{getItem(){return null;}},console,Date};
vm.runInNewContext(common,ctx);
const R=ctx.window.YZRental;
const fields={contractId:'RC-test',rentalType:'other',periods:'9',startDate:'2026-10-19',deliveryDate:'2026-10-18',endDate:'2027-01-16',internalAssetName:'edited asset',internalRentalCountBefore:'6',internalRentalCountNote:'internal note'};
const btn={disabled:false,textContent:''};
const status={textContent:''};
const calls=[];
const stored={contractId:'RC-test',rentalType:'digitalPiano',periods:1,startDate:'2026-10-18',rentFee:2900,internalRentalCountBefore:2,renewalEntries:[{periods:2}],status:'待付款確認'};
let failure=false;
Object.assign(ctx,{R:Object.assign(R,{val:k=>fields[k]||'',setVal:(k,v)=>fields[k]=v,qs:k=>k==='contractSaveStatus'?status:k==='internalRentalCountBox'?{querySelector:()=>btn}:btn,get:async()=>stored,call:async(name,data)=>{calls.push({name,data});if(failure)throw new Error('offline');return {contractId:'RC-test'};},toast:()=>{}}),selected:stored,rentalDateManual:{start:true,end:true},isFinalConfirmStage:()=>true,loadAll:async()=>{},refreshInlineNotificationStatus:()=>{},sanitizeRentalContractForFirestore:p=>p});
vm.runInNewContext(source.slice(source.indexOf('    function countValueOrNull'),source.indexOf('    function internalRentalCountSummaryText')),ctx);
vm.runInNewContext(source.slice(source.indexOf('    function validateInternalRentalCountFor'),source.indexOf('    function actionButtons')),ctx);
vm.runInNewContext(source.slice(source.indexOf('    function syncRentalDatesFromDelivery'),source.indexOf('    function applyDeliveryMethodUi')),ctx);
const saveStart=source.indexOf('    window.saveContract=');
const internalStart=source.indexOf('    window.saveContractChanges=');
vm.runInNewContext(source.slice(saveStart,internalStart),ctx);
const next=source.indexOf('\n    ',source.indexOf('\n    };',source.indexOf('    window.saveInternalRentalCount='))+8);
vm.runInNewContext(source.slice(internalStart,next),ctx);
ctx.saveContract=ctx.window.saveContract;
ctx.collect=()=>({contractId:'RC-test',rentalType:'digitalPiano',startDate:'2026-10-19',endDate:'2027-01-16',rentFee:3000,internalAssetName:'unsaved asset',internalEquipmentCode:'unsaved asset',internalRentalCountBefore:99,internalRentalCountCurrent:100});
(async()=>{
  // An unsaved type/period/date/fee edit must not leak into the count save.
  await ctx.window.saveInternalRentalCount();
  assert.equal(calls.length,1);
  const count=calls.pop().data;
  assert.equal(count.internalRentalCountInitialPeriods,1);
  assert.equal(count.internalRentalCountCurrent,9);
  assert.equal(count.internalAssetName,'edited asset');
  assert.deepEqual(Object.keys(count).sort(),['contractId','internalAssetName','internalEquipmentCode','internalRentalCountBefore','internalRentalCountInitialPeriods','internalRentalCountRenewalPeriods','internalRentalCountCurrent','internalRentalCountAfter','internalRentalCountFormula','internalRentalCountNote'].sort());
  assert.equal(fields.startDate,'2026-10-19','Keep unsaved contract input on screen');
  await ctx.window.saveContractChanges();
  const contract=calls.pop().data;
  assert.equal(contract.startDate,'2026-10-19');
  assert.equal(contract.rentFee,3000);
  assert.equal(contract.rentDays,90);
  assert(!Object.keys(contract).some(k=>k.startsWith('internal')));
  assert.equal(status.textContent,'合約修改已儲存。');
  failure=true;
  await ctx.window.saveContractChanges();
  assert(status.textContent.startsWith('儲存失敗'));
  assert.equal(btn.disabled,false);
  failure=false;
  fields.contractId='';calls.length=0;
  await ctx.window.saveInternalRentalCount();
  assert.equal(calls.length,0,'Internal save cannot silently create a whole contract');
  fields.rentalType='digitalPiano';
  ctx.syncRentalDatesFromDelivery('startDate');
  assert.equal(fields.deliveryDate,'2026-10-19');
  assert.equal(fields.endDate,'2027-01-16','Preserve a manually chosen end date');
  const html=R.renderContractHtml({rentalType:'digitalPiano',startDate:fields.startDate,endDate:fields.endDate});
  assert(html.includes('<td>2026-10-19</td><td>2027-01-16</td><td>90 天</td>'));
  fields.deliveryDate='2026-10-20';ctx.syncRentalDatesFromDelivery('deliveryDate');
  assert.equal(fields.startDate,'2026-10-20');
  console.log('Separate contract/count saves, save failure and formal date synchronization passed');
})().catch(e=>{console.error(e);process.exitCode=1;});
