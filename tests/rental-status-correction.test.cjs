const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const path=require('node:path');
const source=fs.readFileSync(path.join(__dirname,'../rental-admin.html'),'utf8');
const backend=fs.readFileSync(path.join(__dirname,'../functions/index.js'),'utf8');
const handler=source.slice(source.indexOf('    window.correctActiveStatusWithoutNotice='),source.indexOf('    window.markDelivered='));
const stored={status:'待付款確認',startDate:'2026-10-19',endDate:'2027-01-16',rentFee:2900,internalRentalCountBefore:6,officialContractNoticeQueueCreatedAt:'existing-notice',expiryReminderSentForEndDate:''};
let row={...stored},calls=[],message='',rendered;
const btn={disabled:false};
const ctx={window:{},selected:row,R:{val:()=> 'RC-test',qs:()=>btn,get:async()=>row,clean:v=>String(v||'').trim(),inclusiveDays:(a,b)=>a<=b?90:0,call:async(name,patch)=>{calls.push({name,patch});row={...row,...patch};return {contractId:'RC-test'};},toast:m=>{message=m;}},loadAll:async()=>{},renderContract:c=>{rendered=c;}};
vm.runInNewContext(handler,ctx);
(async()=>{
  await ctx.window.correctActiveStatusWithoutNotice();
  assert.equal(calls.length,1);
  assert.equal(calls[0].name,'rentalSaveContractHttp');
  assert.deepEqual(JSON.parse(JSON.stringify(calls[0].patch)),{contractId:'RC-test',status:'租賃中'});
  for(const k of Object.keys(stored).filter(k=>k!=='status')) assert.equal(row[k],stored[k],k+' must be preserved');
  assert.equal(rendered.status,'租賃中');
  assert(message.includes('未重送通知'));
  await ctx.window.correctActiveStatusWithoutNotice();
  assert.equal(calls.length,1,'Already active contracts must not be reconfirmed');
  row={...stored,endDate:''};await ctx.window.correctActiveStatusWithoutNotice();
  assert.equal(calls.length,1,'Missing expiry cannot silently enter reminder flow');
  assert.equal(btn.disabled,false);
  assert(!/queueOfficial|queueCustomer|generatePdf|markDelivered\(/.test(handler));
  const scheduler=backend.slice(backend.indexOf('exports.rentalExpiryReminderDaily'),backend.indexOf('exports.rentalLineRuntimeStatusHttp'));
  assert(scheduler.includes("['租賃中', '到期提醒中', '續約待確認', '續約待付款']"));
  assert(scheduler.includes('left > 5'));
  assert(scheduler.includes('expiryReminderSentForEndDate'));
  console.log('Silent active status correction preserves dates, money, counts and notification history');
})().catch(e=>{console.error(e);process.exitCode=1;});
